// The Daily mark: Sunny rising over a wavy horizon — the same drawing as the phone app (apps/mobile/src/ui/Logo.tsx).
// Single source for resources/logo-*.svg, src/renderer/components/logoPaths.ts and (via render.cjs) the icon files.
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

export const COLORS = { tile: '#171717', sun: '#F6B35E', horizon: '#FBF8F4', face: '#3A2412' };

/** One mark for every size: it was drawn bold enough for 16 px on the phone. */
const DAILY = {
  sun: { cx: 50, cy: 64, r: 21 },
  rays: 'M19.01,48.92 Q13.78,46.51 8.74,44.59 M31.48,34.27 Q28.33,30.03 25.87,25.86 M50.03,29.24 Q49.51,23.88 50.04,18.51 M67.62,34.54 Q71.02,29.32 74.51,23.81 M79.18,48.33 Q85.67,44.75 92.19,42.23',
  horizon: 'M14,67 C17,66.58 26,64.5 32,64.5 C38,64.5 44,67 50,67 C56,67 62,64.58 68,64.5 C74,64.42 83,66.17 86,66.5',
  face: { eyes: 'M43.5 52 L43.5 54 M56.5 52 L56.5 54', smile: 'M44.8 57.6 Q50 61.4 55.2 57.6' },
  clipY: 64,
  /** stroke widths: rays, horizon, eyes, smile */
  width: [7, 6, 3.8, 2.8],
};
export const FULL = DAILY;
export const SMALL = DAILY;

const pen = (d, color, w) => `<path d="${d}" fill="none" stroke="${color}" stroke-width="${w}" stroke-linecap="round" stroke-linejoin="round"/>`;
/** Standalone SVG for a mark (used for the committed .svg files and for rasterising). */
export function markSvg(mark, { size, tile = true }) {
  const clip = `daily-clip-${mark.clipY}`;
  const [wRays, wHorizon, wEyes, wSmile] = mark.width;
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 100 100" width="${size}" height="${size}">`
    + (tile ? `<rect width="100" height="100" rx="24" fill="${COLORS.tile}"/>` : '')
    + `<clipPath id="${clip}"><rect width="100" height="${mark.clipY}"/></clipPath>`
    + `<circle cx="${mark.sun.cx}" cy="${mark.sun.cy}" r="${mark.sun.r}" fill="${COLORS.sun}" clip-path="url(#${clip})"/>`
    + pen(mark.face.eyes, COLORS.face, wEyes) + pen(mark.face.smile, COLORS.face, wSmile)
    + pen(mark.rays, COLORS.sun, wRays)
    + pen(mark.horizon, COLORS.horizon, wHorizon)
    + `</svg>`;
}

const here = dirname(fileURLToPath(import.meta.url));
const app = join(here, '..', '..');
/** Writes the committed sources: resources/logo-full.svg, resources/logo-small.svg, src/renderer/components/logoPaths.ts. */
export function writeSources() {
  writeFileSync(join(app, 'resources', 'logo-full.svg'), markSvg(FULL, { size: 256 }) + '\n');
  writeFileSync(join(app, 'resources', 'logo-small.svg'), markSvg(SMALL, { size: 48 }) + '\n');
  const m = JSON.stringify(DAILY);
  writeFileSync(join(app, 'src', 'renderer', 'components', 'logoPaths.ts'),
    `// Generated by scripts/logo/sunrise.mjs — do not edit by hand (pnpm --filter @worksight/consumer logo).\n`
    + `export interface LogoMark { sun: { cx: number; cy: number; r: number }; rays: string; horizon: string; face: { eyes: string; smile: string }; clipY: number; width: [number, number, number, number] }\n`
    + `const DAILY: LogoMark = ${m} as LogoMark;\n`
    + `export const LOGO: { full: LogoMark; small: LogoMark } = { full: DAILY, small: DAILY };\n`
    + `export const LOGO_COLORS = ${JSON.stringify(COLORS)};\n`);
}
